-- 캐릭터를 **만든 모델**을 남긴다(2026-10-07).
--
-- **이 마이그레이션을 앱보다 먼저 적용한다.** 순서가 반대면 새 앱이 없는 칸
-- (model_id)에 쓰려다 PostgREST 가 PGRST204 로 거절해, 캐릭터 저장이 전부
-- 실패한다. 정면 값은 이미 차감된 뒤라 돈만 나간다.
--
-- 전에는 모델을 남기지 않아 「없는 장면 더 만들기」가 그림체의 기본 모델로
-- 그렸다. 다른 모델로 만든 캐릭터는 나중에 채운 장면만 느낌이 달라졌다.
--
-- 비워 둘 수 있다. 옛 캐릭터는 기록이 없으니 지금처럼 그림체의 기본 모델로
-- 그린다. 모델 목록은 바뀌므로 값을 제약으로 묶지 않는다 — 모르는 값이면
-- 앱이 기본 모델로 떨어뜨린다.
alter table public.characters
  add column if not exists model_id text;
