-- 상세페이지 디자인 레퍼런스의 작은 사본 자리.
--
-- 앞선 두 작업(202609040013, 202609060001)이 라이브러리·갤러리·포스터·카드뉴스·
-- 참고 이미지·캐릭터를 채웠는데 **이 표만 빠졌다.** 그래서 상세페이지(/create)와
-- 리디자인(/redesign)의 「라이브러리에서 불러오기」 창은 셋 중 하나가 아직
-- 원본이다 — 저장되는 것이 AI 가 만든 상세페이지 조각이라 한 장이 2MB 안팎이고,
-- 설계 주석대로 사용자당 열 몇 장이면 창 한 번에 20MB 가 오간다.
--
-- 하는 일: 표에 빈 칸을 하나 추가한다. 그게 전부다.
--   - 기존 데이터를 읽지도 고치지도 않는다
--   - 전부 비어 있어도 되므로 이것만 적용해도 아무것도 안 깨진다
--   - 여러 번 돌려도 안전하다
--
-- 순서: 이 SQL 을 먼저 → 그다음 코드 배포 → 마지막에 백필
--   (`node scripts/backfill-thumbnails.mjs --apply --after-style ""`)
--
-- `path` 에 걸린 형식 제약을 이 칸에는 걸지 않는다 — 사본은 `{원본}.thumb.webp`
-- 로 규칙이 다르다. 참고 이미지에서 내린 것과 같은 판단이다.

alter table public.style_references
  add column if not exists thumb_path text;
