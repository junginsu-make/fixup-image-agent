-- 리디자인 그림 품질을 `low` → `high` 로 올리면서 단가도 함께 올린다.
--
-- 오늘 아침에 $0.19 → $0.02 로 내렸다. 그때는 **값만** 실제(저품질)에 맞춘
-- 것이었다. 이제 사용자가 품질을 올리기로 정했으므로 값도 그 자리로 되돌린다.
--
--   품질 low   → $0.02
--   품질 high  → $0.21   ← 지금
--
-- 왜 리디자인만 저품질이었나 — 외부 프로젝트에서 코드를 그대로 옮겨 오면서
-- 딸려 온 설정이고, 누가 골랐다는 흔적이 없었다. 이 저장소의 다른 도구는 전부
-- `high` 이상이다(`sns-core/generate.ts` 의 `model.quality ?? "high"`, 표준형과
-- 정밀형 플러스는 `max`). **상세페이지는 글자가 많아 저품질이 가장 안 맞는
-- 자리였다.**
--
-- 코드에도 같은 값이 있다(`apps/web/lib/credit-cost.ts`). 두 곳이 갈라지면
-- 차감(코드)과 원가 장부(이 표)가 어긋난다. 한쪽만 고치지 않는다.

update public.model_prices
set unit_cost_usd = 0.21000,
    note = 'gpt-image-2 고품질(quality=high) 공개가 기준. 청구서 대조 전. 2026-09-11 품질을 올리며 $0.02 에서 올림',
    updated_at = now()
where model = 'redesign-openai';
