-- 들어간다. 대신 집계가 `left join model_prices` 라 단가가 없으면
-- `coalesce(p.unit_cost_usd, 0)` 으로 **$0 이 된다.** 오류가 아니라 침묵이다.
-- 코드를 먼저 올리면 그 사이에 만든 그림들이 비용 0원으로 남는다.
