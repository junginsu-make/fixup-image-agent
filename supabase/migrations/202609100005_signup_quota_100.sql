-- 새로 가입한 회원의 기본 한도를 30 → 100 장으로 올린다.
--
-- 30 장으로는 **한 종류만 보고 끝난다.** 상세페이지 8섹션이 28장이라 한 번이면
-- 그 달이 끝나고, 카드뉴스도 19장이라 두 번을 못 돈다. 가입한 사람이 이 도구가
-- 무엇을 하는 물건인지 알려면 여러 기능을 만져 봐야 한다.
--
-- 100 장이면 상세페이지 한 번 + 카드뉴스 한 번 + 포스터 몇 장이 된다.
--
-- ── 얼마나 노출되나 ───────────────────────────────────────────────
--
-- 한 장은 $0.05 다(`packages/shared/src/credit.ts`). 100 장이면 **$5.00**.
-- 자동 승인이라 가입만 하면 바로 쓸 수 있으므로, 100 명이 전부 소진하면
-- 최악 $500 이다. 실패한 요청은 회원에게 안 물리지만 우리는 값을 냈으므로
-- 실제 지출은 그보다 크다 — 실패율 21% 기준 약 $630.
--
--     5 장  →  $0.25  ·  100 명이면   $25
--    30 장  →  $1.50  ·  100 명이면  $150
--   100 장  →  $5.00  ·  100 명이면  $500   ← 지금
--
-- 감당이 안 되면 이 파일과 같은 방식으로 다시 낮춘다. 상한(10000)과 관리자
-- 조정(/admin)은 그대로다.

-- ── 이미 가입한 회원은 건드리지 않는다 ────────────────────────────
--
-- 기본값으로 그 값이 된 사람과 관리자가 일부러 정한 사람을 구별할 수 없다.
-- 올릴 사람은 /admin 에서 한 명씩 정한다.

