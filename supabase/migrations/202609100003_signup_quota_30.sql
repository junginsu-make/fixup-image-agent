-- 새로 가입한 회원의 기본 한도를 5 → 30 장으로 올린다.
--
-- 2026-07-29(`202607290001`)에 승인 절차를 없애면서 30 → 5 로 낮췄었다. 승인이
-- 막던 것은 "낯선 사람이 우리 돈을 쓰는 것"이고, 그건 절차가 아니라 한도로
-- 막는 편이 낫다는 판단이었다. 그 판단 자체는 그대로다 — **다만 5장이 너무
-- 적었다.** 카드뉴스 한 벌이 대여섯 장이라, 5장으로는 이 서비스가 무엇을 하는
-- 물건인지 한 번도 못 보고 끝난다. 체험이 안 되는 한도는 비용을 아끼는 게
-- 아니라 가입자를 버리는 것이다.
--
-- 노출은 여섯 배가 된다. 100명이 가입해 전부 소진하면 장당 $0.21 기준
-- 최악 $105 → $630 이다. 상한(10000)과 관리자 조정(/admin)은 그대로라,
-- 감당이 안 되면 이 파일과 같은 방식으로 다시 낮출 수 있다.

-- ── 이미 가입한 회원은 건드리지 않는다 ────────────────────────────
