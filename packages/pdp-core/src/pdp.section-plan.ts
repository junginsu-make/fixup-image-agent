import type { SectionBlueprint } from "./types";

/**
 * **몇 장으로 만들 것인가.**
 *
 * ── 무엇이 문제였나 ──────────────────────────────────────────
 *
 * 프롬프트가 장수를 못 박고 있었다 — 사진 경로는 「5~6개」, 글 경로는 「4~7개」.
 * 할 말이 세 가지인 제품에도 여섯 장을 요구하면, **나머지 세 장은 채우려고
 * 지어낸 것**이 된다. 그 자리에서 나오는 문장이 「사용 후 일상이 조금 더
 * 가벼워집니다」 같은 것들이고, 프롬프트에는 그런 문구를 하나씩 금지한 흔적이
 * 남아 있다. 증상을 막았을 뿐 원인은 장수 강제였다.
 *
 * 같은 자리에 **인물 필수·후기 카드 6~12개·베네핏 3개 고정**도 있었다. 후기
 * 지시는 특히 나빴다 — 바로 아래 줄의 「근거 없는 후기 개수를 만들지 말 것」과
 * 정면으로 부딪혔다. 한 프롬프트 안에서 서로 반대말을 하고 있었다.
 *
 * 설계 §9.1 이 「고정 5~6/4~7장 강제가 아니라 **전달해야 할 사실과 구매자
 * 질문**으로 선택한다」, 「인물 필수·후기 카드·베네핏 3개는 모든 상품의 고정
 * 조건에서 제거한다」고 적은 자리다.
 *
 * ── 풀면 강제를 코드로 옮겨야 한다 ───────────────────────────
 *
 * 지금까지 장수를 막는 것은 **프롬프트 문구뿐**이었다. 코드에는 상한이 한 줄도
 * 없었다. 문구는 부탁이지 강제가 아니다 — 모델이 서른 장을 내놓으면 서른 장이
 * 그대로 생성 대기열에 들어가고, 한 장마다 값이 나간다.
 *
 * 그래서 장수를 푸는 대신 **상한을 코드로 지킨다.**
 */

/**
 * 한 페이지에 만들 수 있는 최대 섹션 수.
 *
 * 옛 글 경로의 상한(7)보다 넉넉하되 무한하지 않게 잡는다. 한 장이 곧 이미지
 * 한 장이고 값과 시간이 든다 — 열 장이면 이미 긴 페이지다.
 *
 * **화면과 서버가 이 값을 함께 쓴다**(설계 §9.1). 두 벌로 적으면 화면은
 * 허용하는데 서버가 자르는 날이 온다.
 */
export const MAX_PLANNED_SECTIONS = 10;

/**
 * 상한을 넘으면 자른다.
 *
 * **최소 장수는 강제하지 않는다.** 할 말이 하나인 제품에 빈 장을 붙이는 것이
 * 모자란 페이지보다 나쁘다(설계 §9.1: 「최소 1섹션도 의도된 구성이라면 허용」).
 */
export function clampSections<T>(sections: T[]): T[] {
  return sections.length > MAX_PLANNED_SECTIONS ? sections.slice(0, MAX_PLANNED_SECTIONS) : sections;
}

/**
 * 몇 장으로 만들지 **무엇으로 정하는지** 모델에게 말한다.
 *
 * `hasPlanInstruction` 이면 **사용자가 장수를 지정했을 수 있다**고 말한다.
 * 안 그러면 이 블록이 「장수를 먼저 정하지 않는다」고 하고, 사용자가 적은
 * 「섹션을 다섯 개로」를 **뒤에서 덮는다** — 적었는데 아무 일도 안 일어나는
 * 그 증상이 새 칸에서 되살아난다(U-06).
 */
export function sectionCountRules(options: { hasPlanInstruction?: boolean } = {}): string {
  const 사용자지정 = options.hasPlanInstruction
    ? `
- **사용자가 구성 요청에서 장수를 지정했으면 그 수를 따른다.** 위 원칙보다 앞선다.
  다만 기술 상한(${MAX_PLANNED_SECTIONS}장)은 넘을 수 없다.`
    : "";

  return `# 몇 장으로 만들 것인가

**장수를 먼저 정하지 않는다.** 전달해야 할 제품 사실과 구매자가 실제로 던질
질문을 먼저 꼽고, 그것을 담는 데 필요한 만큼만 만든다.

- 할 말이 적은 제품은 적게 만든다. **빈 장을 채우려고 문장을 지어내지 않는다.**
  그렇게 나온 문장은 아무 제품에나 붙는 일반론이 된다.
- 한 섹션이 한 가지 일을 한다. 두 가지를 담아야 하면 나누고, 나눌 것이 없으면 합친다.
- 기술 상한은 ${MAX_PLANNED_SECTIONS}장이다. 넘기면 뒤가 잘린다.
- 사람이 나오는 장면, 후기, 혜택 나열은 **이 제품에 필요할 때만** 넣는다. 모든
  상품에 들어가야 하는 고정 구성이 아니다.${사용자지정}`;
}

export type SectionPlanGapKind = "no_sections" | "no_headline" | "no_reassurance";

export interface SectionPlanGap {
  kind: SectionPlanGapKind;
  /** 사용자가 읽을 말. 무엇이 없는지와 무엇을 하면 되는지. */
  message: string;
}

/**
 * 장수를 풀었으니 **모자란 구성도 통과한다.** 그래서 무엇이 빠졌는지는 따로 본다
 * (설계 §9.1: 「최소 1섹션도 의도된 구성이라면 허용하되 필수 정보 부족을 검사한다」).
 *
 * **막지 않는다. 말할 뿐이다.** 적은 장수가 의도된 구성일 수도 있다.
 */
export function sectionPlanGaps(sections: SectionBlueprint[]): SectionPlanGap[] {
  if (sections.length === 0) {
    return [{ kind: "no_sections", message: "구성안에 섹션이 하나도 없습니다. 다시 만들어 주세요." }];
  }

  const gaps: SectionPlanGap[] = [];
  const 값있음 = (value: string | undefined) => Boolean(value?.trim());

  if (!sections.some((section) => 값있음(section.headline))) {
    gaps.push({
      kind: "no_headline",
      message: "제목이 있는 섹션이 하나도 없습니다. 페이지가 아무 말도 하지 않습니다.",
    });
  }

  /*
    **망설임을 다루는 문장이 페이지 어딘가에는 있어야 한다.**

    좋은 점만 나열하면 읽는 사람은 속으로 반박하며 읽는다. 다만 **모든 섹션에**
    요구하지는 않는다 — 그러면 같은 말이 반복되고, 그것이 원래의 고정 조건 강제와
    같은 실수다.
  */
  if (!sections.some((section) => 값있음(section.trust_or_objection_line))) {
    gaps.push({
      kind: "no_reassurance",
      message: "살까 말까 망설이는 이유를 다루는 문장이 한 곳도 없습니다. 가격·효과·실패 걱정 중 하나는 페이지가 먼저 꺼내는 편이 좋습니다.",
    });
  }

  return gaps;
}
