/**
 * **고친 전략으로 구성을 다시 짠다.**
 *
 * ── 무엇이 문제였나 ──────────────────────────────────────────
 *
 * 「전체 전략」칸은 그냥 글상자였다. 고쳐도 **아무 일도 안 일어난다** — 섹션은
 * 그대로다. 그런데 화면은 그 사실을 말하지 않아, 사용자는 전략을 고치고 다음
 * 단계로 넘어가 **고친 전략이 반영된 줄 알고** 이미지를 만든다. 한 장에 값이
 * 드는데, 나온 그림은 옛 전략을 따른다.
 *
 * 반대편에는 「설정 바꿔 다시 만들기」뿐이었다. 그것은 업로드 화면까지 되돌려
 * 구성안을 통째로 버린다 — 고쳐 둔 문구도 함께 사라진다.
 *
 * **고친 전략으로 구성만 다시 짜는 길이 없었다**(U-11).
 *
 * 설계 §4.2: 「전체 전략 수정은 요약 수정이다. 섹션 재설계는 별도의 『이
 * 전략으로 구성 다시 만들기』 동작이며 이전 revision을 보존한다.」
 */

import { sanitizePromptText } from "./pdp.claim-policy";

/**
 * 전략 글의 길이 상한. **화면과 서버가 이 값을 함께 쓴다.**
 *
 * 화면이 모르면 사용자가 긴 글을 붙여넣고 눌렀을 때 서버가 400 을 내고,
 * 그 오류는 구성 화면에서 보이지도 않는다.
 */
export const MAX_STRATEGY_LENGTH = 2000;

export function buildStrategyDirective(strategy: string | undefined): string {
  // 전략 칸은 사용자가 자유롭게 쓰는 글이다. 지시를 흉내내지 못하게 한다.
  const text = sanitizePromptText(strategy ?? "");
  // 빈 지시로 값을 쓰지 않는다. 안 고쳤으면 평소 기획과 같아야 한다.
  if (!text) return "";

  /*
    **전략이 먼저 온다.**

    긴 규칙 뒤에 붙이면 묻힌다 — 같은 이유로 심사 지적(`buildRevisionDirective`)도
    프롬프트 맨 앞에 놓는다.
  */
  return [
    "[사용자가 고친 전체 전략 — 이 전략으로 구성을 다시 짠다]",
    text,
    "위 전략을 페이지 전체의 뼈대로 삼아 섹션 구성과 카피를 **다시** 설계할 것.",
    "이전 구성안을 조금 고치는 것이 아니라, 이 전략에서 출발해 새로 짤 것.",
  ].join("\n");
}
