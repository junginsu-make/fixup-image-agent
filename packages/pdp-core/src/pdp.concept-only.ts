import type { ProductKind } from "./pdp.offering";

/**
 * **사진 없이 실물을 팔 때**(N-2, 설계 §9.1).
 *
 * ── 무엇이 문제인가 ────────────────────────────────────────
 *
 * 글로만 「나무 도마를 팝니다」라고 적으면, 우리는 **나무 도마를 지어낸다.**
 * 그 그림에는 실제로 파는 물건과 다른 결·색·모양이 그려진다. 사용자는 그것을
 * 상세페이지에 올리고, 사는 사람은 그 사진을 보고 산다.
 *
 * 설계 §9.1: 「참고용 외형 없는 실물 입력은 **임의 제품을 실제 제품처럼 생성
 * 승인하지 않는다.** 실제 제품 자료 부족을 표시하고 원본 제공 또는 **개념
 * 시안임을 명시하는 흐름**으로 처리한다」.
 *
 * ── 막지 않고 알린다 ───────────────────────────────────────
 *
 * 생성을 막지는 않는다. 개념 시안이 필요한 경우가 실제로 있다 — 아직 만들지
 * 않은 물건을 소개하거나, 분위기만 먼저 보는 경우다. **막으면 그 사람들이
 * 못 쓴다.**
 *
 * 대신 셋을 한다.
 *   1. 자료가 없다는 것을 **말한다**
 *   2. 사진을 올리면 된다고 **길을 알려 준다**
 *   3. 그대로 만들면 **개념 시안임을 프롬프트와 화면에 명시한다**
 *
 * ── 무형 상품은 해당 없다 ──────────────────────────────────
 *
 * 서비스·디지털 상품에는 보여 줄 실물이 없다. 그때의 이미지는 원래 사용
 * 장면·결과 장면이라 「실제와 다르다」는 말이 성립하지 않는다.
 */

export interface ProductEvidenceInput {
  /** 무엇을 파는가. 사용자가 안 밝혔으면 `undefined`. */
  productKind?: ProductKind;
  /** 실제 제품이 찍힌 사진이 있는가. 업로드 사진이나 승인된 대표 이미지. */
  hasProductPhoto: boolean;
}

export interface ConceptOnlyNotice {
  /** 개념 시안으로 다루어야 하는가. */
  conceptOnly: boolean;
  /** 사용자에게 보여 줄 말. 해당 없으면 빈 문자열. */
  message: string;
}

const NOTICE =
  "파는 물건의 사진이 없어서 이미지를 상상으로 그립니다. 실제 제품과 색·모양·글자가 다를 수 있습니다. 제품 사진을 올리면 실제 모습으로 만듭니다.";

/**
 * 개념 시안으로 다루어야 하는가.
 *
 * **모를 때는 경고하지 않는다.** 상품 종류를 안 밝힌 사람에게 「사진이
 * 없습니다」라고 하면, 무형 상품을 파는 사람도 그 말을 듣는다. 잘못된 경고는
 * 사용자가 경고 전체를 무시하게 만든다.
 */
export function conceptOnlyNotice(input: ProductEvidenceInput): ConceptOnlyNotice {
  const 실물이다 = input.productKind === "physical";
  if (!실물이다 || input.hasProductPhoto) return { conceptOnly: false, message: "" };
  return { conceptOnly: true, message: NOTICE };
}

/**
 * 개념 시안일 때 이미지 프롬프트에 더하는 지시.
 *
 * **지어내지 말라고만 하면 부족하다**(`productKindRule` 이 이미 그렇게 한다).
 * 그 말만으로는 모델이 그럴듯한 물건을 그리고, 그 그림은 **실제 제품처럼
 * 보인다.** 로고·글자·상표를 빼고 형태를 단정하지 않게 해서, 보는 사람이
 * 「이 물건 그대로」라고 읽지 않도록 만든다.
 */
export function conceptOnlyPromptRule(): string {
  return `- 실제 제품 사진이 없다. 이 이미지는 **개념 시안**이다.
  상표·로고·제품명 글자를 그리지 마라. 특정 브랜드로 읽히는 형태도 피하라.
  제품을 화면 가득 확대하지 말고, 사용 장면·분위기 쪽으로 잡아라.`;
}
