import type { ImageLook } from "@fixup/shared";
import { sanitizePromptText } from "./pdp.claim-policy";

/**
 * **구성 요청과 장면 요청은 다른 일이다**(U-06).
 *
 * ── 무엇이 문제였나 ──────────────────────────────────────────
 *
 * 「추가 지시」 칸이 하나뿐이었고, 그 값은 **이미지 생성에만** 갔다. 칸의 예시도
 * 장면 지시다 — 「배경은 밤, 창밖에 네온」.
 *
 * 그래서 사용자가 「섹션을 다섯 개로」나 「존댓말로 써 주세요」를 적으면
 * **아무 일도 안 일어난다.** 기획은 그 말을 본 적이 없고, 이미지 프롬프트에
 * 실려 가서는 그릴 수 있는 것이 없다. 사용자는 적었는데 안 된 이유를 모른다.
 *
 * 그림체도 같았다. 기획은 **사진인지 그림인지 모른 채** 장면을 쓴다 — 「제품을
 * 손에 들고 웃는 인물 사진」이라 적어 놓고 결과는 일러스트가 된다.
 *
 * 설계 §6.3: 그림체는 「기획과 생성 **양쪽 전달**」, 구성·문구 요청은 「현재 추가
 * 지시에서 **분리**」.
 */

/**
 * 사용자가 적은 **구성·문구 요청**을 기획 지시로.
 *
 * 장면 지시(`userInstruction`)와 섞지 않는다. 저쪽은 그림을 정하고 이쪽은
 * 섹션과 카피를 정한다.
 */
export function buildPlanInstructionRules(instruction: string | undefined): string {
  // 사용자가 자유롭게 쓰는 글이라 지시를 흉내내지 못하게 한다.
  const text = sanitizePromptText(instruction ?? "");
  // 빈 지시로 프롬프트를 늘리지 않는다.
  if (!text) return "";

  return [
    "# 사용자가 적은 구성·문구 요청",
    text,
    "",
    "위 요청을 섹션 구성과 카피에 반영할 것.",
    /*
      **근거를 무르게 하지 않는다.**

      「효능을 강조해 주세요」 한 줄로 없는 사실이 생기면 안 된다. 요청은
      **무엇을 어떻게 쓸지**를 정하지, 무엇이 사실인지를 정하지 않는다.
    */
    "다만 이 요청이 근거 규칙을 풀지는 않는다 — 확인되지 않은 사실을 새로 만들지 말 것.",
  ].join("\n");
}

const LOOK_RULE: Record<ImageLook, string> = {
  // 레퍼런스의 결을 따른다. 기획이 사진이라 단정하면 어긋난다.
  auto: "이 페이지의 그림은 첨부한 **디자인 레퍼런스의 결**을 따른다. 장면을 쓸 때 사진인지 그림인지 단정하지 말 것.",
  photoreal: "이 페이지의 그림은 **사진**이다. 촬영할 수 있는 장면으로 쓸 것.",
  anime: "이 페이지의 그림은 **애니메이션 그림체**다. 촬영 용어(렌즈·조리개) 대신 장면과 연출로 쓸 것.",
  "3d": "이 페이지의 그림은 **3D 렌더**다. 촬영 용어 대신 장면과 연출로 쓸 것.",
  illustration: "이 페이지의 그림은 **일러스트**다. 촬영 용어 대신 장면과 연출로 쓸 것.",
};

/**
 * 그림체를 기획에게도 알린다.
 *
 * 전에는 생성에만 갔다. 기획이 「사진」을 전제로 장면을 쓰면, 일러스트를 고른
 * 사용자는 **그릴 수 없는 장면 지시**를 받는다.
 */
export function lookPlanningRule(look: ImageLook | undefined): string {
  return look ? LOOK_RULE[look] ?? "" : "";
}

/**
 * 「광고답게 만들라」는 지시. **그림체에 따라 말을 고른다**(U-06).
 *
 * 전에는 한 문장으로 못 박혀 있었다 — 「단순한 제품 누끼나 **그래픽이 아닌** …
 * 고품질 **광고 사진** 느낌으로 기획할 것」. 그것이 「# 섹션 구성 원칙(강제)」
 * 블록 안, 그림체 규칙보다 **뒤에** 있었다.
 *
 * 일러스트를 고른 사용자에게 그 줄은 「그림으로 기획하지 마라」다. 앞에서
 * 「일러스트다」라고 말해도 뒤가 이긴다 — 이 저장소가 `pdp.reference-policy`
 * 주석에 실측으로 적어 둔 그 함정이다.
 */
export function adPolishRule(look: ImageLook | undefined): string {
  const 사진 = !look || look === "photoreal" || look === "auto";
  return 사진
    ? "- 각 섹션의 이미지는 단순한 제품 누끼나 그래픽이 아닌 소비자의 구매 전환을 유도할 수 있는 고품질 광고 사진 느낌으로 기획할 것"
    : "- 각 섹션의 이미지는 단순한 제품 누끼가 아닌, 소비자의 구매 전환을 유도할 수 있는 고품질 광고 이미지로 기획할 것. 결은 위에서 정한 그림체를 따른다";
}
