/**
 * 장(크레딧)과 실제 돈을 잇는다.
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────
 *
 * 관리자는 사람마다 한도를 **장**으로 정한다. 그런데 장의 뜻이 모델마다 달랐다
 * (2026-09-08 실측).
 *
 *   모델              가중치   실제 단가    장 하나당 실제 돈
 *   gpt-image-2         4      $0.1780       $0.0445
 *   nano-banana-pro     3      $0.1500       $0.0500
 *   nano-banana-2       2      $0.1200       $0.0600   ← 가장 비쌈
 *   nano-banana         1      $0.0390       $0.0390   ← 가장 쌈
 *
 * 같은 「1장」이 $0.039 에서 $0.060 까지, **54% 차이**가 났다. 싼 모델을 쓰는
 * 사람이 손해를 봤다.
 *
 * 게다가 정수 가중치 하나로는 **크기를 담을 자리가 없다.** 같은 GPT Image 2 라도
 * 정사각 1024 는 $0.219, 포스터 2:3 은 $0.178 로 23% 차이가 난다.
 *
 * ── 그래서 장을 돈에 붙인다 ─────────────────────────────────
 *
 * 관리자는 계속 장으로 한도를 정하고, 장의 뜻만 못 박는다. 모델도 크기도
 * 저절로 따라오고, 단가표가 바뀌어도 손댈 곳이 없다.
 */

/**
 * 장 하나가 얼마인가. **$0.05** (2026-09-08 사용자 결정).
 *
 * 지금 쓰던 가중치들의 평균쯤이라, 관리자 화면에 이미 들어 있는 한도 숫자의
 * 뜻이 크게 안 바뀐다.
 */
export const CREDIT_UNIT_USD = 0.05;

/**
 * 기획 한 번의 글 모델 값. **실측이 아니라 어림이다.**
 *
 * 이 저장소에는 글 모델의 단가표가 없다(`model_prices` 에는 그림 모델뿐이다).
 * 그래서 공개 단가로 계산했다 — Claude Sonnet 기준 입력 $3/M · 출력 $15/M.
 *
 *   기획      입력 1.5k + 출력 600  ≈ $0.0045 + $0.0090 = $0.014
 *
 * 실제 토큰을 재기 시작하면 이 숫자를 지우고 그 값을 쓴다. **한 곳에 모아 둔
 * 이유가 그것이다.**
 */
export const LLM_PLAN_USD = 0.014;

/**
 * 그림 한 장을 읽는 값 — 문법 읽기·사람 읽기.
 *
 *   그림 한 장  입력 2k(그림 포함) + 출력 300 ≈ $0.0060 + $0.0045 ≈ $0.010
 *
 * 첨부가 늘면 이 값도 그만큼 는다. 그래서 한 번이 아니라 **장수로 센다.**
 */
export const LLM_VISION_READ_USD = 0.010;

/**
 * 이 요청에 들어간 글 모델 값.
 *
 * 그림값에 견주면 작지만 **공짜는 아니다.** 첨부를 여러 장 넣고 기획을 여러 번
 * 돌리면 그림 한 장 값을 넘는다.
 */
export function llmCostUsd(input: { planCalls?: number; visionReads?: number }): number {
  const plans = Math.max(0, input.planCalls ?? 0);
  const reads = Math.max(0, input.visionReads ?? 0);
  return Number((plans * LLM_PLAN_USD + reads * LLM_VISION_READ_USD).toFixed(4));
}

/**
 * 이만큼 쓰면 몇 장인가.
 *
 * **올림한다.** 내림하면 $0.049 짜리가 0장이 되어 아무리 만들어도 한도가 안 준다.
 * 반올림도 같은 구멍이 있다($0.024 → 0장).
 *
 * 0원이면 0장이다 — 실패해서 아무것도 안 받았을 때 그렇다. 다만 **1원이라도
 * 썼으면 최소 1장**이다.
 */
export function creditUnits(usd: number): number {
  if (!Number.isFinite(usd) || usd <= 0) return 0;
  return Math.max(1, Math.ceil(usd / CREDIT_UNIT_USD));
}
