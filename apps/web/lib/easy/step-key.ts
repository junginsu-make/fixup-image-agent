import { createHash } from "node:crypto";

/**
 * 대신 부르는 **단계마다 다른 요청 식별자**.
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────
 *
 * Easy 는 포스터 라우트 셋을 대신 부르며 원래 요청의 헤더를 그대로 넘긴다.
 * 그런데 그중 **둘이 각자 예약한다** — 기획(`plan`)과 생성(`generate`)이다.
 *
 * 예약은 같은 식별자를 두 번 받으면 `duplicate_request` 로 거절한다. 그것이
 * 그 열쇠의 일이다 — 같은 요청이 두 번 들어와도 한 번만 깎으려는 것. 그래서
 * 열쇠를 그대로 물려주면 **두 번째 단계가 반드시 409 로 막힌다.**
 *
 *   2026-09-21 운영: 400 을 고치자 그 자리에서 409 가 나왔다.
 *
 * 포스터 화면은 이 함정에 안 빠진다. 기획과 생성이 **사용자의 서로 다른
 * 누름**이고 누를 때마다 새 열쇠가 나가기 때문이다. Easy 는 한 번 누르면
 * 셋이 이어 도는 구조라 우리가 갈라 줘야 한다.
 *
 * ── 왜 그냥 새로 만들지 않나 ─────────────────────────────────
 *
 * 매번 난수를 뽑으면 **되보내기가 두 번 깎인다.** 같은 Easy 요청이 다시 들어와도
 * 안쪽 열쇠가 달라져 예약이 새 요청으로 보인다.
 *
 * 바깥 열쇠에서 **정해진 방식으로** 뽑으면 그 성질이 산다 — 같은 요청은 같은
 * 열쇠, 다른 단계는 다른 열쇠.
 */

/** 서버가 받아 주는 꼴. `membership/api.ts` 의 검사와 같은 모양이어야 한다. */
const 자리 = [8, 4, 4, 4, 12];

/**
 * 바깥 열쇠와 단계 이름에서 이 단계의 열쇠를 만든다.
 *
 * **4판 UUID 꼴로 맞춘다.** 서버는 판 번호 자리(13번째 글자)가 `1`~`5`,
 * 변형 자리(17번째)가 `8`·`9`·`a`·`b` 인 것만 받는다. 해시를 그대로 자르면
 * 그 두 자리가 아무 값이나 되어 **열여섯 번에 한 번쯤 거절당한다** — 그런
 * 실패는 재현이 안 돼서 원인을 못 찾는다.
 */
export function stepIdempotencyKey(base: string, step: string): string {
  const hex = createHash("sha256").update(`${base}:${step}`).digest("hex");

  const 판 = "4";
  // 변형 자리는 네 글자 중 하나여야 한다. 해시 한 글자를 그 넷으로 접는다.
  const 변형 = "89ab"[parseInt(hex[16]!, 16) % 4]!;
  const 몸통 = hex.slice(0, 12) + 판 + hex.slice(13, 16) + 변형 + hex.slice(17, 32);

  let at = 0;
  return 자리.map((길이) => 몸통.slice(at, (at += 길이))).join("-");
}
