/**
 * **레퍼런스를 올리는 문의 상한. 화면과 서버가 같은 값을 본다.**
 *
 * 설계 §12 는 「숫자는 실제 대표 긴 페이지로 메모리 측정 후 **정책 상수와
 * UI 에서 일치**시킨다」고 했다. 두 벌로 적으면 화면이 「20MB」라고 써 둔 채
 * 서버만 조여지는 날이 온다 — 그때 사용자가 보는 것은 이유 없는 413 이다.
 *
 * **이 파일은 서버 전용이 아니다.** 화면이 그대로 읽어 안내에 쓴다.
 */

/**
 * 본문을 여기까지만 읽는다.
 *
 * 설계 §12: 「업로드 제한의 기존 20MiB 를 디코드된 입력 예산의 출발값으로
 * 사용한다. JSON wire 는 base64 팽창과 metadata 예산을 별도로 계산해 같은
 * 정책에서 파생한다.」 `PDP_JSON_LIMIT` 과 같은 식으로 뽑는다.
 */
export const STYLE_REFERENCE_JSON_LIMIT = Math.ceil(20 * 1024 * 1024 * 4 / 3) + 1024 * 1024;

/**
 * 그래서 **파일 한 장이 얼마까지 되는가.**
 *
 * base64 는 3바이트를 4글자로 늘린다. 되돌려 계산한 값을 MB 로 내림한다 —
 * 실제로는 조금 더 통과하지만, **약속은 내림한 쪽으로 한다.** 「20MB 까지
 * 된다」고 해 놓고 20MB 가 막히는 것이 그 반대보다 훨씬 나쁘다.
 */
export const STYLE_REFERENCE_MAX_MB = Math.floor(
  (STYLE_REFERENCE_JSON_LIMIT * 3) / 4 / 1024 / 1024,
);

/**
 * 펼쳤을 때 여기까지만 받는다.
 *
 * ── 왜 40MP 인가 (2026-09-20 실측) ───────────────────────────
 *
 * **바이트 크기로는 못 막는다.** 16383×16383 단색 PNG 는 수백 KB 로 눌린다.
 * 그래서 화소 수로 잰다.
 *
 * 처음에 `image-encoding.ts` 의 12MP 를 가져왔다가 되돌렸다. 그 값은 **무손실
 * 재인코딩**이 그림 전체를 메모리에 올리기 때문에 나온 수인데(39.7MP 에서
 * 483MB), **이 길은 그 인코딩을 안 탄다** — 원본 바이트를 창고에 그대로 올리고
 * 줄인 사본만 따로 만든다. 무엇보다 상세페이지 레퍼런스가 1080×15000(16.2MP)
 * 이라, 12MP 로 막으면 이 기능의 주 사용 사례가 통째로 막힌다.
 *
 * 이 바이트가 실제로 가는 두 곳을 39.7MP(6300×6300, 결이 있는 난수 그림,
 * 파일 3MB)로 쟀다. sharp 0.35.4 / libvips 8.18.6:
 *
 *   문지기(metadata 만)              0ms,  RSS +0MB
 *   조각내기(resize 1024 → jpeg)    88ms,  RSS +1MB
 *   작은 사본(resize 512 → webp)    72ms,  RSS +1MB
 *   무손실 인코딩                    이 길은 안 탄다(12MP 상한에 걸려 던진다)
 *
 * 줄이는 길은 libvips 가 흘려 읽어서 펼치지 않는다. 40MP 에서도 한 건이
 * 1MB·100ms 다. `grid-thumbnail.ts` 의 `GRID_MAX_PIXELS` 와 우연히 같은 값이나,
 * **근거는 그 상수가 아니라 위 실측이다** — 그쪽 주석은 「낯선 바이트를 받는
 * 문이 아니라서 넉넉하다」고 적혀 있고, 여기는 바로 그 문이다.
 */
export const STYLE_REFERENCE_MAX_PIXELS = 40_000_000;

/** 화면이 쓰는 한 줄. 서버 오류 문구와 같은 수를 쓴다. */
export const STYLE_REFERENCE_LIMIT_HINT =
  `PNG · JPEG · WebP, ${STYLE_REFERENCE_MAX_MB}MB 이하, ${STYLE_REFERENCE_MAX_PIXELS / 1_000_000}백만 화소 이하`;
