import { imageCreditUnits } from "../credit-cost";

/**
 * **쪼갠 것은 우리 사정인데 값은 사용자가 냈다**(F-7-7).
 *
 * 리디자인의 「나머지 섹션 생성」은 자기 자신을 한 장씩 다시 부른다. 그래서
 * 여덟 장 채우기는 요청 여덟 번이고, 요청마다 `creditUnits` 가 **따로 올림**했다.
 *
 * 실측(2026-09-21, `imageCreditUnits`):
 *
 *   모델                          8장 한 번에   1장씩 8번   더 내던 것
 *   gpt-image-2.5-flare (운영)         34          40        6장 (15%)
 *   redesign-openai (키 없을 때)       27          32        5장 (16%)
 *   redesign-google                    21          24        3장 (13%)
 *
 * 열 장이면 운영 모델 기준 43장 대 50장이다. **운영에서 실제로 청구되는 것은
 * fal 모델**이다(`billedModel`) — `redesign-openai` 는 키가 없어 옛 직접
 * 호출로 떨어졌을 때의 값이다.
 *
 * 쪼개는 이유는 **우리 쪽 사정**이다 — 한 요청에서
 * 여덟 장을 그리면 시간 상한(300초)에 걸리고, 중간에 끊기면 앞 장까지 잃는다.
 *
 * 설계 §7.2: 「한 번의 '전체 생성'은 **논리 작업 단위**로 예상 금액을 계산한다.
 * 내부 청크/섹션 분할 때문에 **올림이 반복되지 않는다.** 부분 성공 시 성공
 * 결과의 같은 단가 스냅샷 합계를 **한 번 올림**해 확정한다.」
 *
 * ── 어떻게 세나 ─────────────────────────────────────────────
 *
 * 청크가 받는 값은 「**여기까지의 논리 누적**에서 **앞서 청구한 만큼**을 뺀 것」이다.
 *
 *   앞서 낸 것 = creditUnits(단가 × 앞 청크들의 장수)
 *   여기까지   = creditUnits(단가 × (앞 장수 + 이번 장수))
 *   이번 청구  = 여기까지 − 앞서 낸 것
 *
 * 여덟 번을 더하면 `creditUnits(단가 × 8)` 이 된다 — **올림이 딱 한 번**이다.
 * 중간에 멈춰도 그때까지의 논리 금액만 낸다.
 *
 *   1번째: ceil(3.3)=4   − 0        = 4
 *   2번째: ceil(6.6)=7   − 4        = 3
 *   3번째: ceil(9.9)=10  − 7        = 3
 *   …
 *   8번째: ceil(26.4)=27 − 24       = 3     합계 27
 *
 * ── 화면은 자리만 말한다. 그래도 자리가 금액을 움직인다 ────
 *
 * 화면은 장수도 금액도 보내지 않는다. 그런데 **자리를 통해 금액이 움직인다** —
 * 앞자리를 크게 부르면 「앞서 낸 것」이 커져 이번 청구가 준다. 2026-09-21
 * 리뷰에서 `jobIndex=1e17` 이면 예약도 차감도 **0** 이 되는 것이 실측으로
 * 드러났다. 0 은 그냥 싼 것이 아니다 — `reserve_generation` 의 동시 생성
 * 검사가 `elsif p_units > 0 then` 안에 있고 월 한도 검사도 `+ 0` 이라 **한도를
 * 다 쓴 계정이 무제한으로 유료 이미지를 만든다.**
 *
 * 그래서 `readRedesignForm` 이 경계에서 `1 <= jobIndex <= jobTotal <= 10` 을
 * 재고, 여기서도 한 번 더 조인다.
 *
 * **그래도 남는 것이 있다.** 조인 뒤에도 매 요청 마지막 자리를 보내면 한 장에
 * 한 칸까지 덜 낼 수 있다(운영 모델 기준 5장 대신 4장). 「앞서 낸 것」이
 * 서버의 기록이 아니라 **화면이 말한 자리**이기 때문이다. 요청당 최대 1장,
 * 약 $0.05 다 — 지금은 감수 범위로 둔다. 없애려면 첫 청크에서 서버가 작업
 * 표를 발급하고 앞 청크들의 `requested_units` 합을 서버가 읽어야 한다
 * (`docs/bugs/pdp-validation/progress.md` 의 남은 빚).
 */

/** 논리 작업 하나가 가질 수 있는 최대 청크 수. 섹션 상한과 같다. */
const MAX_JOB_CHUNKS = 10;

export type ChunkBillingInput = {
  /** 값을 매길 모델. **실제로 그리는** 모델이어야 한다. */
  modelId: string;
  /**
   * 논리 작업 안에서 이 청크가 **몇 번째인가**(1부터).
   *
   * 0 이거나 없으면 쪼개지 않은 것으로 본다 — 옛 화면이나 바깥 호출이
   * 들어와도 값이 틀어지면 안 된다.
   */
  jobIndex: number;
  /** 이 청크가 만들려는 장수. */
  chunkCount: number;
};

/**
 * 이 청크가 받을 장수를 세는 자.
 *
 * 돌려주는 함수에 **실제로 만든 장수**를 넣는다. 예약 때는 만들려는 수를,
 * 확정 때는 만들어진 수를 넣으면 둘이 같은 셈에서 나온다.
 */
export function chunkCreditUnits({ modelId, jobIndex, chunkCount }: ChunkBillingInput): (made: number) => number {
  /*
    **여기서도 조인다.** 경계(`readRedesignForm`)가 이미 막지만, 이 계산기를
    부르는 입구가 나중에 하나 더 생길 수 있다. 큰 자리를 그냥 믿으면 예약이
    0 이나 NaN 으로 나가고, 0 은 동시 생성 검사와 월 한도 검사를 **통째로
    건너뛴다**(2026-09-21 실측).
  */
  const index = Number.isFinite(jobIndex) ? Math.min(Math.max(0, Math.floor(jobIndex)), MAX_JOB_CHUNKS) : 0;
  const size = Number.isFinite(chunkCount) ? Math.min(Math.max(0, Math.floor(chunkCount)), MAX_JOB_CHUNKS) : 0;

  // 앞 청크들이 만든 장수. 청크 크기가 고르다는 전제다 — 화면이 한 장씩 부른다.
  const 앞장수 = index > 1 ? (index - 1) * Math.max(1, size) : 0;
  const 앞서낸것 = imageCreditUnits(modelId, 앞장수);

  return (made: number) => {
    /*
      **만든 장수도 조인다.** 여기를 안 조이면 `made` 가 무한일 때 두 항이
      모두 무한이 되어 차가 `NaN` 이고, 그것이 그대로 예약으로 나간다. SQL 의
      `p_units < 0` 검사는 NULL 이라 **통과한 뒤** `not null` 제약에서 터지는데,
      사용자에게는 「사용량을 확인하지 못했습니다」만 뜨고 원인은 안 남는다
      (2026-09-04 에 겪은 것과 같은 증상).

      한 논리 작업의 최대 장수가 곧 한 번에 만들 수 있는 최대 장수다.

      **모르는 값은 안전한 쪽으로 민다.** 무한은 상한(전액)으로, 숫자가
      아니면 0 으로 — 「만든 것이 없다」가 그쪽의 뜻이다.
    */
    const 만든것 = Number.isNaN(made) ? 0 : Math.min(Math.max(0, Math.floor(made)), MAX_JOB_CHUNKS);

    /*
      **못 만들었으면 0 이 저절로 나온다.** 앞서 낸 것에서 앞서 낸 것을 빼기
      때문이다. 전에는 `if (만든것 <= 0) return 0` 을 따로 뒀는데, 그 줄을
      지워도 어떤 시험도 안 빨개졌다 — 식이 이미 같은 답을 낸다. **어떤
      시험으로도 가를 수 없는 방어는 방어가 아니라 잡음이다.**
    */

    /*
      **앞서 낸 것을 빼고 남는 것이 0 일 수 있다.** 값이 싼 모델을 여러 장
      만들면 누적 올림이 한 칸도 안 움직이는 청크가 생긴다. 그것이 맞다 —
      그 장의 값은 앞 청크에서 이미 올림에 실려 나갔다.
    */
    /*
      **세 값이 모두 조여 있어 결과는 늘 유한하다.** 전에는 여기에
      `if (!Number.isFinite(청구)) …` 한 줄을 더 뒀는데, 위 셋을 조인 뒤로는
      **어떤 입력으로도 그 가지에 닿지 않았다**(변이로 확인). 가를 수 없는
      방어는 방어가 아니라 잡음이다 — 막는 일은 조이는 쪽에 맡긴다.
    */
    return Math.max(0, imageCreditUnits(modelId, 앞장수 + 만든것) - 앞서낸것);
  };
}
