/**
 * **답을 읽을 수 있는 모양으로 다듬는다**(2026-09-28 사용자 신고).
 *
 * > 지금 챗에 결과물들이 한 줄로만 쭉 나오고 있습니다. 그래서 가독성이 매우
 * > 떨어집니다.
 *
 * ── 왜 한 줄로 나왔나 ──────────────────────────────────────
 *
 * 두 가지가 겹쳤다.
 *
 *   ① **화면이 줄바꿈을 버렸다.** 글을 그냥 넣으면 HTML 이 `\n` 을 빈칸
 *      하나로 뭉갠다. 모델이 줄을 나눠 보내도 소용이 없었다
 *   ② **줄을 나누라고 시키지 않았다.** 프롬프트는 「두세 문장으로 짧게」만
 *      말했다. 짧게는 맞는데 **어떻게 놓을지**를 안 정해 줬다
 *
 * 둘 다 고쳐야 한다. 하나만 고치면 그대로다.
 *
 * ── 이 파일이 하는 일 ──────────────────────────────────────
 *
 * 모델이 보낸 글을 화면에 놓기 전에 다듬는다. **모양만 만진다** — 낱말을
 * 바꾸거나 줄이지 않는다. 내용을 손대기 시작하면 「근거대로 답한다」가 깨진다.
 *
 * 모델은 시키지 않아도 마크다운을 쓴다(`**굵게**`, `- 목록`). 화면은 글을
 * 그대로 그리므로 별표가 **그대로 보인다.** 그것을 걷어 낸다.
 */

/** 한 답에 남길 줄 수. 넘으면 좁은 칸에서 스크롤만 길어진다. */
const 줄최대 = 20;

/** 굵게·기울임 표시를 걷어 낸다. 안의 글자는 그대로 둔다. */
function 강조를푼다(line: string): string {
  return line
    .replace(/\*\*(.+?)\*\*/g, "$1")
    .replace(/__(.+?)__/g, "$1")
    // 한 낱말을 감싼 별표만 푼다. 곱셈 기호로 쓴 별표를 건드리지 않는다.
    .replace(/(^|\s)\*([^\s*][^*]*?)\*(?=$|[\s.,)])/g, "$1$2");
}

/**
 * 목록 표시를 이 저장소가 쓰는 가운뎃점으로 맞춘다.
 *
 * 마크다운의 `-` 와 `*` 는 화면에 그대로 나온다. 번호(`1.`)는 그대로 둔다 —
 * 차례가 있는 것은 번호가 맞다.
 */
function 목록을맞춘다(line: string): string {
  return line.replace(/^\s*[-*•]\s+/, "· ");
}

/**
 * **모양만 다듬는다.** 낱말은 그대로 둔다.
 *
 * 하는 일은 넷이다.
 *   · 마크다운 강조와 목록 표시를 걷는다
 *   · 줄 끝의 빈칸을 턴다
 *   · 빈 줄이 여럿이면 하나로 줄인다
 *   · 너무 길면 자른다
 */
export function tidyReply(text: string): string {
  if (typeof text !== "string") return "";

  const 줄들 = text
    .replace(/\r\n?/g, "\n")
    .split("\n")
    .map((line) => 목록을맞춘다(강조를푼다(line)).replace(/[ \t]+$/g, ""));

  const 다듬은것: string[] = [];
  for (const line of 줄들) {
    // 빈 줄이 이어지면 하나만 남긴다.
    if (line.trim() === "" && 다듬은것.at(-1)?.trim() === "") continue;
    다듬은것.push(line);
  }

  return 다듬은것.slice(0, 줄최대).join("\n").trim();
}

/**
 * **한 덩어리로 온 글을 문장마다 끊는다.**
 *
 * 모델이 줄을 안 나눠 보내는 일이 있다. 시키는 것만으로는 안 되는 날이
 * 있어서, 그때도 읽히게 한다.
 *
 * **문장이 셋을 넘을 때만** 손댄다. 두 문장짜리 답을 굳이 쪼개면 오히려
 * 뚝뚝 끊겨 보인다.
 */
export function breakLongParagraph(text: string, 기준 = 3): string {
  const 한줄인가 = !text.includes("\n");
  if (!한줄인가) return text;

  /*
    마침표·물음표·느낌표 뒤에서 끊는다. 숫자 사이의 점(1.5)과 줄임표는
    문장 끝이 아니다.
  */
  const 문장들 = text
    .split(/(?<=[.?!])\s+(?=[^\s])/)
    .filter((문장) => 문장.trim() !== "");

  if (문장들.length <= 기준) return text;
  return 문장들.join("\n");
}

/** 화면에 놓기 전에 거치는 한 자리. */
export function formatReply(text: string): string {
  return tidyReply(breakLongParagraph(tidyReply(text)));
}
