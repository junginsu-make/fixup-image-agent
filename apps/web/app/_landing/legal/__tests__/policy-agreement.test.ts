import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { purchaseExpiresAt, subscriptionExpiresAt } from "@fixup/shared";
import { TERMS_DOC } from "../documents";

/**
 * **약관과 설명서와 코드가 같은 말을 하는가**(2026-09-28).
 *
 * ── 왜 이 시험이 필요한가 ──────────────────────────────────
 *
 * 같은 규칙이 **세 곳**에 적혀 있다.
 *
 *   ① 약관 — 법적 효력을 갖는 문서
 *   ② 설명서 — 사용자가 실제로 읽는 글
 *   ③ 코드 — 실제로 도는 것
 *
 * 셋이 갈라지면 **분쟁 시 약관이 이긴다.** 그래서 설명서가 약관보다 불리하게
 * 적혀 있으면 그 안내는 지킬 수 없는 약속이고, 코드가 약관보다 짧게 만료시키면
 * 그것은 약관 위반이다.
 *
 * 실제로 갈라져 있었다(2026-09-28 발견) —
 *
 *   약관 제6조  「유료 크레딧에는 별도의 유효기간을 두지 않습니다」
 *   코드        구매 크레딧을 **3개월**에 만료시킨다
 *
 * 약관이 무기한을 약속하는데 코드가 3개월에 지우고 있었다. 사용자가 그 사이에
 * 크레딧을 잃었다면 약관을 근거로 다툴 수 있는 상태였다.
 *
 * ── 무엇을 재는가 ──────────────────────────────────────────
 *
 * **글자가 아니라 규칙이 같은지**를 잰다. 문장을 통째로 비교하면 말투만
 * 다듬어도 붉어져서, 결국 시험을 지우게 된다.
 */

const web = join(__dirname, "..", "..", "..", "..");
const 설명서 = readFileSync(join(web, "app", "guide", "account", "page.tsx"), "utf8");
const 약관 = TERMS_DOC.body;

describe("구매 크레딧 유효기간", () => {
  /**
   * **코드가 정본이다.** 약관은 코드가 하는 것을 적어야 한다 — 반대가 아니다.
   * 약관이 더 길게 약속하면 지킬 수 없고, 더 짧게 적으면 사용자를 속인다.
   */
  it("코드가 3개월 뒤에 만료시킨다", () => {
    const 산날 = "2026-01-15T00:00:00.000Z";
    const 끝나는날 = new Date(purchaseExpiresAt(산날));
    const 달차이 =
      (끝나는날.getUTCFullYear() - 2026) * 12 + (끝나는날.getUTCMonth() - 0);

    expect(달차이, "코드가 바뀌었으면 약관과 설명서도 함께 고쳐야 한다").toBe(3);
  });

  /**
   * **기산일은 「계정에 지급된 날」이다**(2026-09-29 사용자: 약관을 코드에 맞춘다).
   *
   * 코드는 만료를 크레딧을 넣는 순간부터 센다(`credit_purchase_expiry(now())`).
   * 결제 연동이 없어 운영자가 확인하고 넣으므로 「구매일」과 날짜가 다를 수 있다.
   * 계정 화면(「지급일로부터 3개월」)과 설명서(「계정에 들어온 날부터」)도 같다.
   */
  it("약관이 그 기간을 적는다", () => {
    expect(약관, "약관이 코드와 다른 기간을 약속한다").toContain("계정에 지급된 날부터 3개월");
    expect(약관, "옛 기산일이 남아 있다").not.toContain("구매일부터 3개월");
  });

  it("설명서도 그 기간을 적는다", () => {
    expect(설명서).toContain("3개월까지");
  });

  /** 옛 약속이 남아 있으면 그것이 근거가 된다. */
  it("무기한이라는 옛 문구가 남아 있지 않다", () => {
    expect(약관, "약관이 아직 무기한을 약속하고 있다").not.toContain("별도의 유효기간을 두지 않습니다");
  });
});

describe("구독 크레딧은 이월되지 않는다", () => {
  it("코드가 받은 때부터 한 달 뒤에 만료시킨다", () => {
    const 받은날 = new Date("2026-03-10T00:00:00.000Z");
    const 끝나는날 = new Date(subscriptionExpiresAt(받은날));

    expect(끝나는날.getTime()).toBeGreaterThan(받은날.getTime());
    expect(끝나는날.getTime() - 받은날.getTime()).toBeLessThan(32 * 24 * 60 * 60 * 1000);
  });

  it.each([
    ["약관", () => 약관],
    ["설명서", () => 설명서],
  ])("%s 가 이월되지 않는다고 적는다", (_이름, 글) => {
    expect(글()).toContain("이월되지 않습니다");
  });
});

describe("구독 크레딧은 배정한 날부터 한 달 쓴다", () => {
  /**
   * **2026-10-09 사용자 결정 — 약관을 코드에 맞춘다.**
   *
   * 전에는 달력으로 끊었다(25일에 받아도 그 달 말일에 사라짐). 이제 구독을 배정한 날부터
   * 한 달이 한 주기이고, 구독이 켜져 있는 동안 주기마다 자동으로 다시 들어온다.
   */
  it("코드가 25일에 준 것을 다음 달 25일에 끝낸다", () => {
    expect(subscriptionExpiresAt("2026-03-25T03:00:00.000Z")).toBe("2026-04-25T03:00:00.000Z");
  });

  /** 실제로 지급하는 것은 DB 함수다. DB 도 「시작 + n달 ~ 시작 + (n+1)달」로 끊는지 본다. */
  it("DB 함수도 배정한 때부터 한 달씩 끊는다", () => {
    const 장부 = readFileSync(
      join(web, "..", "..", "supabase", "migrations", "202610090001_subscription_auto_cycle.sql"),
      "utf8",
    );

    expect(장부).toContain("starts_at := (v_start + make_interval(months => n)) at time zone 'Asia/Seoul'");
    expect(장부).toContain("expires_at := (v_start + make_interval(months => n + 1)) at time zone 'Asia/Seoul'");
  });

  it("약관이 결제 주기를 시작한 날부터 한 달로 정의한다", () => {
    expect(약관).toContain("구독을 시작한 날부터 한 달");
    expect(약관, "옛 달력 주기가 남아 있다").not.toContain("매월 1일부터 말일까지");
  });

  it("약관이 주기가 끝나는 때 사라진다고 적는다", () => {
    expect(약관).toContain("그 결제 주기가 끝나는 때까지");
    expect(약관, "옛 말일 소멸이 남아 있다").not.toContain("지급된 달의 말일");
  });

  it("약관이 결제 확인 뒤 지급이라고 적지 않는다", () => {
    expect(약관).not.toContain("그 달의 결제를 확인한 뒤 지급");
  });

  it("설명서도 배정한 날부터 한 달이라고 적는다", () => {
    expect(설명서).toContain("배정한 날부터 한 달");
    expect(설명서, "옛 결제 확인 안내가 남아 있다").not.toContain("그 달 결제를 확인하면");
  });
});

describe("무료 크레딧의 화면 이름", () => {
  /**
   * 약관은 「무료 크레딧」, 잔액 화면은 「추가 지급」이라고 부른다. 운영자가
   * 수동으로 넣어 주는 몫이다(2026-09-29 사용자: 가입 후 30~100 크레딧 수동
   * 지급 예정). 회원이 화면에서 본 이름으로 약관을 찾을 수 있어야 한다.
   */
  it("약관이 화면의 이름을 밝힌다", () => {
    const 지갑 = readFileSync(join(web, "app", "_components", "credit-wallet.tsx"), "utf8");

    expect(지갑).toContain('"추가 지급"');
    expect(약관).toContain("화면에는 「추가 지급」으로 표시");
  });
});

describe("환불 기준", () => {
  /**
   * **구독과 구매를 가른다.** 하나로 뭉뚱그리면 「크레딧을 썼으니 환불 안 된다」가
   * 구매 크레딧에까지 적용되고, 그것은 법이 보장하는 권리를 침해한다.
   */
  it("약관이 구독과 구매를 갈라 적는다", () => {
    expect(약관).toContain("구매 크레딧: 사용하지 않은 잔액을 환불합니다");
    expect(약관).toContain("서비스 제공이 개시된 주기의 구독료는 환불하지 않습니다");
  });

  /**
   * **나눌 수 있는 이용 단위는 미사용분을 돌려준다.**
   *
   * 전자상거래법이 가분적 디지털콘텐츠의 미제공 부분에 청약철회를 인정한다.
   * 이 문장을 지우면 약관이 법보다 불리해지고, 그런 조항은 효력이 없다.
   */
  it("가분적 이용 단위의 미사용분 환불을 약관이 보장한다", () => {
    expect(약관, "이 문장을 지우면 약관이 법보다 불리해진다").toContain(
      "사용하지 않은 부분의 환불을 거절하지 않습니다",
    );
  });

  /** 법정 권리는 약관으로 못 줄인다. 그 선언이 남아 있어야 한다. */
  it("법정 권리를 제한하지 않는다는 선언이 남아 있다", () => {
    expect(약관).toContain("법령이 보장하는 소비자의 권리를 제한하지 않습니다");
  });

  it("설명서가 약관과 같은 기준을 적는다", () => {
    expect(설명서).toContain("환불되지 않습니다");
    expect(설명서).toContain("원화로 환산");
  });
});

describe("구독 해지", () => {
  it.each([
    ["약관", () => 약관, "이미 결제한 결제 주기가 끝날 때 해지됩니다"],
    ["설명서", () => 설명서, "이미 결제한 기간까지는 그대로"],
  ])("%s 가 기간 끝까지 유지된다고 적는다", (_이름, 글, 문장) => {
    expect(글()).toContain(문장);
  });
});

describe("월 구독이 있다는 것", () => {
  /** 구독 상품이 생겼는데 약관이 충전형만 말하고 있었다. */
  it("일회성 충전 상품이라는 옛 문구가 없다", () => {
    expect(약관, "약관이 아직 구독을 모른다").not.toContain("일회성 충전 상품으로 자동 갱신되지 않습니다");
  });

  it("구독 크레딧을 정의한다", () => {
    expect(약관).toContain("구독 크레딧");
    expect(약관).toContain("구매 크레딧");
  });
});

describe("바뀐 약관을 알리는 절차", () => {
  /**
   * **회원에게 불리한 변경이다.** 유효기간이 무기한에서 3개월로 줄고 환불이
   * 제한된다. 약관 제12조가 「원칙적으로 30일 전에 알린다」고 정하고 있다.
   */
  it("시행일이 적혀 있고 이전 판을 갈음한다고 밝힌다", () => {
    expect(약관).toMatch(/시행일: 2026년 \d{1,2}월 \d{1,2}일/);
    expect(약관, "이전 판과의 관계를 안 밝히면 어느 것이 유효한지 다툰다").toContain("갈음합니다");
  });

  it("사전 고지 의무가 약관에 남아 있다", () => {
    expect(약관).toContain("30일 전에 알리며");
  });
});
