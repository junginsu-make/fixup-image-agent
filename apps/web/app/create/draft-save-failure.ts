/**
 * **저장이 실패했을 때 무슨 말을 할 것인가**(E-6-3-a).
 *
 * ── 왜 한 줄로는 모자랐나 ────────────────────────────────────
 *
 * 대표 최대 초안을 재 봤다 — 섹션 10장에 원본·인물·레퍼런스까지 담으면
 * **하나가 63.4MB** 다(2026-09-21 실측). 스무 개면 1.27GB 라, 브라우저 저장
 * 한도에 닿는 것이 드문 일이 아니다.
 *
 * 그때 화면이 하던 말은 「작업을 저장하지 못했습니다」 한 줄이었다. **무엇을
 * 하면 되는지가 없다.** 게다가 자동 저장이 30초마다 같은 실패를 되풀이한다.
 *
 * ── 잃은 것과 안 잃은 것을 갈라 말한다 ──────────────────────
 *
 * 저장은 `store.put` 한 번이라, 실패해도 **앞서 저장한 사본은 살아남는다**
 * (IndexedDB 는 트랜잭션을 통째로 취소한다). 잃는 것은 이번 변경분뿐이다.
 * 그 사실을 안 말하면 사용자는 **다 날아간 줄 알고** 돌아오지 않는다.
 */

/** 브라우저가 저장 공간이 없다고 할 때 쓰는 이름. */
const QUOTA_ERROR_NAMES = new Set(["QuotaExceededError", "NS_ERROR_DOM_QUOTA_REACHED"]);

export function draftSaveFailureMessage(error: unknown): string {
  const name = error instanceof Error ? error.name : "";

  if (QUOTA_ERROR_NAMES.has(name)) {
    return (
      "브라우저 저장 공간이 가득 찼습니다. 시작 화면에서 오래된 작업을 지운 뒤 다시 저장해 주세요. " +
      "마지막으로 저장한 내용은 그대로 있습니다."
    );
  }

  return "작업을 저장하지 못했습니다.";
}
