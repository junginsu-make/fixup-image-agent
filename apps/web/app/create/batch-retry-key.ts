/**
 * **일괄 생성은 다시 누를 때마다 새로 예약했다**(K-05).
 *
 * ── 무엇이 문제였나 ─────────────────────────────────────────
 *
 * `apiJson` 은 POST 에 `x-idempotency-key` 가 없으면 **매번 새로 만든다**
 * (`pdp-utils.ts`). 그런데 일괄 생성(`/pdp/images/batch`)은 그 머리글을 안
 * 실었다. 그래서 통신이 끊겨 사용자가 다시 누르면
 *
 *   새 열쇠 → 새 예약 → **이미 만든 것을 또 만들고 또 받는다**
 *
 * 단건 경로는 섹션마다 열쇠를 붙잡아 둔다(`retryRequestKeysRef`). 일괄만
 * 빠져 있었다.
 *
 * ── 여기서 닫는 것과 못 닫는 것 ─────────────────────────────
 *
 * **닫는 것**: 같은 묶음을 다시 누르면 같은 열쇠가 간다. 서버가 중복을
 * 알아보고 거절하므로 **두 번 받지 않는다.**
 *
 * **못 닫는 것**: 설계가 말한 「동일 **결과** 회수」는 서버 job 이 켜져야
 * 한다(`PDP_JOBS_ENABLED` 가 꺼져 있다). 지금은 「두 번 안 받는다」까지다.
 */

/**
 * 이 묶음을 가리키는 이름.
 *
 * **차례까지 센다.** 같은 섹션들이라도 순서가 다르면 다른 요청이다 — 인물
 * 사진을 「첫 섹션에만」 쓸 때 자리에 따라 결과가 달라진다.
 *
 * 열쇠 자체가 아니라 **열쇠를 담아 두는 칸 이름**이다. 실제 열쇠는 단건
 * 경로와 같은 `retryRequestKeysRef` 가 들고 있다.
 */
export function batchRetryKeyId(sectionKeys: readonly string[]): string {
  const 묶음 = (sectionKeys ?? []).join("|");
  return `batch:${묶음}`;
}
