import { ANGLE_KEYWORD_RULES, DEFAULT_SECTION_ANGLE } from "@fixup/pdp-core";
import { characterAngleLabel } from "../../lib/character-library";

/**
 * 자동 각도가 **무엇을 보고 고르는지** 사실대로 말한다(U-05).
 *
 * ── 왜 고쳤나 ────────────────────────────────────────────────
 *
 * 전에는 「자동은 섹션 설명을 **읽어** 어울리는 각도를 하나씩 고릅니다」였다.
 * 실제로는 낱말 몇 개를 대조하고, 아무것도 안 걸리면 한 각도로 굳는다.
 * 리디자인 경로는 섹션 설명이 늘 비어 있어 **언제나** 기본값이다.
 *
 * 규칙이 나쁘다는 말이 아니다 — 잘 돈다. 나쁜 것은 **판단처럼 보이게 말한
 * 것**이다. 사용자는 「AI 가 봤겠지」 하고 넘기고, 왜 이 각도인지 물을 생각을
 * 못 한다.
 *
 * ── 왜 여기 있나 ─────────────────────────────────────────────
 *
 * `.tsx` 안에 두면 시험이 **값으로 못 잰다** — 문구가 보간이라 소스 대조로는
 * 규칙 표를 실제로 쓰는지 알 수 없다. 이 저장소가 같은 자리에서 여러 번 겪었다.
 */
/*
  **낱말 → 각도**로 적는다. 규칙 이름(`label`)을 쓰면 「뒷모습 → 뒷모습」처럼
  헛돈다 — 사용자가 알고 싶은 것은 **어떤 말을 적으면 어느 각도가 오는가**다.
*/
export const AUTO_ANGLE_HINT = `자동은 섹션 설명에서 낱말을 찾아 각도를 고릅니다(${ANGLE_KEYWORD_RULES.map(
  (rule) => `「${rule.examples.join("·")}」→ ${characterAngleLabel(rule.angle)}`,
).join(", ")}). 아무 낱말도 없으면 기본값인 ${characterAngleLabel(DEFAULT_SECTION_ANGLE)}를 씁니다.`;

/**
 * 리디자인 화면의 안내.
 *
 * 거기서는 캐릭터를 **섹션이 만들어지기 전에** 정한다. 그래서 읽을 설명이 늘
 * 비어 있고 자동은 **언제나 기본값 한 장**이다.
 *
 * 전에는 「왼쪽 45도」를 손으로 적어 뒀다. 기본값을 바꾸면 그 줄만 거짓이 되고
 * 잡는 시험이 없다 — 같은 상수에서 짓는다.
 */
export const REDESIGN_AUTO_ANGLE_HINT = `자동은 ${characterAngleLabel(
  DEFAULT_SECTION_ANGLE,
)} 한 장을 씁니다. 두 눈이 보여 얼굴이 남습니다.`;
