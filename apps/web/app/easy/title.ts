/**
 * 대화 제목을 **첫 프롬프트 앞부분**으로 짓는다 (설계 §4-1).
 *
 * **LLM 을 한 번 더 부르지 않는다.** 값이 들고, 제목 때문에 기다리게 된다.
 * 왼쪽 레일에서 어느 대화인지 알아보게 하는 것이 목적이고, 그 목적에는 앞부분
 * 스무 자면 넉넉하다.
 */

/** 레일 한 줄에 들어가는 길이. 넘으면 말줄임표가 붙는다. */
const MAX = 20;

export function easyTitle(firstPrompt: string): string {
  /*
   * **줄바꿈을 한 칸으로 만든다.** 여러 줄을 친 경우 제목에 줄바꿈이 들어가면
   * 레일 한 줄이 무너진다. 이어지는 공백도 한 칸으로 줄인다.
   */
  const 한줄 = firstPrompt.replace(/\s+/gu, " ").trim();

  /*
   * **빈 제목을 그대로 둔다.** 「제목 없음」 같은 것을 코드가 지어내지 않는다 —
   * 화면이 빈 제목을 어떻게 보일지는 화면이 정한다. 여기서 글을 만들면 그 글이
   * 표에 저장되고, 나중에 화면이 바뀌어도 옛 글이 남는다.
   */
  if (!한줄) return "";

  // 자를 때 낱말을 쪼개지 않으려 들지 않는다. 한국어는 낱말 경계가 공백이 아닌
  // 경우가 많아, 억지로 맞추면 오히려 짧아지고 알아보기 어려워진다.
  //
  // **자른 끝의 공백은 뗀다.** 「카메라를 …」처럼 공백과 말줄임표가 붙으면
  // 말이 끊긴 것이 아니라 빠뜨린 것처럼 보인다.
  if (한줄.length <= MAX) return 한줄;
  return `${한줄.slice(0, MAX).trimEnd()}…`;
}
