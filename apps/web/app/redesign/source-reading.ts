/**
 * **원본을 얼마나 읽었는지 사용자에게 할 말.**
 *
 * ── 왜 생겼나 ──────────────────────────────────────────────
 *
 * 「일부 구간 전사 실패」가 토스트로 나갔고, 바로 다음 줄의 토스트가 같은 틱에
 * 덮어 **한 번도 화면에 안 떴다.** 통째로 못 읽은 경우는 아예 말이 없었다.
 *
 * ── 왜 중요한가 ────────────────────────────────────────────
 *
 * 전사가 없으면 서버 프롬프트가 「원본 전사: 없음(이미지만으로 추정)」으로
 * 바뀐다. 그러면 **「전사에 없는 수치·인증·효능을 만들지 마라」는 제동과
 * `verified_facts` 가 함께 사라진다.** 결과는 나오지만 근거가 다른 물건이다.
 *
 * 버리는 것 자체는 괜찮다. 안 알리는 것이 문제다.
 *
 * ── 멀쩡할 때는 아무 말도 안 한다 ──────────────────────────
 *
 * 다 읽었는데 「다 읽었습니다」를 띄우면, 다음에 진짜 경고가 떴을 때 사용자가
 * 같은 자리를 또 무시한다.
 */

export interface SourceReading {
  /** 못 읽은 구간 수. */
  failedBatches: number;
  /** 한 자도 못 읽었는가. */
  readFailed: boolean;
}

export function sourceReadingNotice(reading: SourceReading): string {
  if (reading.readFailed) {
    return "원본 상세페이지의 글을 읽지 못했습니다. 사진만 보고 추정해 만듭니다. 원본의 수치와 인증 문구는 결과에 실리지 않습니다.";
  }

  if (reading.failedBatches > 0) {
    return `원본 ${reading.failedBatches}개 구간을 읽지 못했습니다. 읽은 범위로 만듭니다. 그 구간의 문구와 수치는 결과에 빠질 수 있습니다.`;
  }

  return "";
}
