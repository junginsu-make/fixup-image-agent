import assert from 'node:assert/strict';
import { stagingSupabase } from './lib/staging-supabase.mjs';
const api=await stagingSupabase();
const email='ledger-boundary@example.test',password='fixture-password-123';
const list=await api.json('/auth/v1/admin/users');
let user=list.users.find(user=>user.email===email);
if(!user)user=await api.json('/auth/v1/admin/users',{method:'POST',body:{email,password,email_confirm:true}});
const session=await api.json('/auth/v1/token?grant_type=password',{key:api.status.ANON_KEY,method:'POST',body:{email,password}});
const project='30000000-0000-4000-8000-000000000008';
await api.json('/rest/v1/sns_projects?on_conflict=id',{method:'POST',headers:{Prefer:'resolution=ignore-duplicates'},body:{id:project,user_id:user.id,title:'HTTP boundary fixture',model_id:'nano-banana',ratio:'4:5',language:'ko',data:{}}});
const response=await api.request(`/rest/v1/sns_projects?id=eq.${project}`,{key:session.access_token,method:'PATCH',body:{data:{reservationId:'client-controlled',executionFlow:{stage:'result'}}}});
console.log(`AUTHENTICATED_DATA_WRITE_STATUS=${response.status}`);
assert.equal(response.status,403,'Authenticated HTTP must not overwrite server execution data.');
const title=await api.request(`/rest/v1/sns_projects?id=eq.${project}`,{key:session.access_token,method:'PATCH',body:{title:'Still editable'}});
assert.ok(title.ok,'Ordinary title editing must remain available.');
const privateRows=await api.request('/rest/v1/generation_runs?select=id',{key:session.access_token});
assert.equal(privateRows.status,403);
const rpc=await api.request('/rest/v1/rpc/begin_generation_v2',{key:session.access_token,method:'POST',body:{p_input:{}}});
assert.equal(rpc.status,403);
const secretPath=`${user.id}/fixture/result.json`;
const upload=await fetch(new URL(`/storage/v1/object/generation-internal/${secretPath}`,api.base),{method:'POST',headers:{apikey:api.status.SERVICE_ROLE_KEY,authorization:`Bearer ${api.status.SERVICE_ROLE_KEY}`,'content-type':'application/json','x-upsert':'true'},body:'{"fixture":true}'});
assert.ok(upload.ok,`Private storage fixture upload ${upload.status}`);
const download=await fetch(new URL(`/storage/v1/object/authenticated/generation-internal/${secretPath}`,api.base),{headers:{apikey:api.status.ANON_KEY,authorization:`Bearer ${session.access_token}`}});
assert.ok(!download.ok,'Private response must not be downloadable by an authenticated member.');
console.log('T04/T23 actual Supabase Auth + PostgREST grants + private Storage boundary passed.');
